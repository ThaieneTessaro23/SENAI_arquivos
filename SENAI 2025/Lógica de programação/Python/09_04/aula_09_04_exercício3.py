dia = int(input("Digite um número de 1 a 7: "))

if(dia == 1):
    print("É Domingo!")
elif(dia == 2):
    print("É Segunda!")
elif(dia == 3):
    print("É Terça!")
elif(dia == 4):
    print("É Quarta!")
elif(dia == 5):
    print("É Quinta!")
elif(dia == 6):
    print("É Sexta!")
elif(dia == 7):
    print("É Sabádo!")
else:
    print("Dia inválido!")