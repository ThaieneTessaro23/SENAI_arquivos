import pandas as pd

import os

from google.colab import drive
drive.mount('/content/drive')

notas = {
    "Nome": [],
    "Matéria": [],
    "Nota": []
}

deseja_continuar = "S"
while deseja_continuar == "S":
  print("Digite os dados: ")
  nome = input("Nome: ")
  materia = input("Matéria: ")
  nota = input("Nota: ")

  notas["Nome"].append(nome)
  notas["Matéria"].append(materia)
  notas["Nota"].append(nota)

  deseja_continuar = input("Deseja continuar? (S/N): ")

print(notas)

df = pd.DataFrame(notas)

os.makedirs('/content/drive/MyDrive/arquivos_salvos', exist_ok=True)

df.to_csv("/content/drive/MyDrive/arquivos_salvos/notas.txt", sep="\t", index=False)

