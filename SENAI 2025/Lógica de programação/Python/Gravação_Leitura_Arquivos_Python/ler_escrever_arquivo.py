import pandas as pd

import os

from google.colab import drive
drive.mount('/content/drive')

dados = {
    "Nome": [],
    "Idade": [],
    "Cidade": []
}

deseja_continuar = "S"
while deseja_continuar == "S":
  print("Digite os dados: ")
  nome = input("Nome: ")
  idade = input("Idade: ")
  cidade = input("Cidade: ")

  dados["Nome"].append(nome)
  dados["Idade"].append(idade)
  dados["Cidade"].append(cidade)

  deseja_continuar = input("Deseja continuar?(S/N): ")

print(dados)

df = pd.DataFrame(dados)

print("📁 Escolha o formato para salvar os dados: ")
print("1 - CSV")
print("2 - JSON")
print("3 - TXT")
escolha_arquivo = input("Digite o número do formato desejado: ")

os.makedirs('/content/drive/MyDrive/arquivos_salvos', exist_ok=True)

if escolha_arquivo == "1":
  df.to_csv("/content/drive/MyDrive/arquivos_salvos/dados.csv", index=False)
  print("Dados salvos com sucesso em 'dados.cvs'!😁✅")
elif escolha_arquivo == "2":
  df.to_json("/content/drive/MyDrive/arquivos_salvos/dados.json", orient="records", indent=4)
  print("Dados salvos com sucesso em 'dados.json'!😁✅")
elif escolha_arquivo == "3":
  df.to_csv("/content/drive/MyDrive/arquivos_salvos/dados.txt", sep="\t", index=False)
  print("Dados salvos com sucesso em 'dados.txt'!😁✅")
else:
  print("⚠️ Tipo de arquivo inválido!")

ler_arquivo = input("🗂️ Deseja carregar os dados salvos? (S/N): ")
if ler_arquivo == "S":
  print("📁 Escolha o formato do arquivo que você deseja ler: ")
  print("1 - CSV")
  print("2 - JSON")
  print("3 - TXT")
  escolha_formato = input("Digite o número do formato desejado: ")

  try:
    if escolha_formato == "1":
      arquivo_lido = pd.read_csv('/content/drive/MyDrive/arquivos_salvos/dados.csv')
    elif escolha_formato == "2":
      arquivo_lido = pd.read_json('/content/drive/MyDrive/arquivos_salvos/dados.json')
    elif escolha_formato == "3":
      arquivo_lido = pd.read_csv('/content/drive/MyDrive/arquivos_salvos/dados.txt')
    else:
      print("⚠️Formato de arquivo inválido!")
      arquivo_lido = None
    print(arquivo_lido)

  except:
    print("⚠️Erro na leitura do arquivo!")