CREATE VIEW VW_FUNCIONARIOS_SUPERMERCADO AS
SELECT 	F.FUN_NOME,
		F.FUN_EMAIL,
        F.FUN_JORNADA_TRABALHO,
        S.SUP_RAZAO_SOCIAL
