USE BD_SUPERMERCADO_FUNCIONARIO_PRODUTO_CONSUMIDOR;

/* PROGRAMAÇÃO COM BD - VIEW*/
CREATE VIEW VW_PRODUTOS_SUPERMERCADO AS
SELECT 	P.PRO_NOME AS "NOME DO PRODUTO",
		P.PRO_CODIGO_BARRAS AS "CÓDIGO DE BARRAS",
        P.PRO_PRECO AS "PREÇO DO PRODUTO",
        S.SUP_RAZAO_SOCIAL AS "NOME DO SUPERMERCADO",
        S.SUP_CNPJ AS "CNPJ",
        S.SUP_ENDERECO_CIDADE AS "CIDADE DO SUPERMERCADO",
        S.SUP_ENDERECO_ESTADO AS "ESTADO DO SUPERMERCADO"
FROM 	PRODUTO P
JOIN	SUPERMERCADO_PRODUTO SP ON (P.PRO_ID = SP.FK_PRO_ID)
JOIN 	SUPERMERCADO S ON (SP.FK_SUP_CNPJ = S.SUP_CNPJ);

SELECT * FROM VW_PRODUTOS_SUPERMERCADO;


/* PROGRAMAÇÃO COM BD - STORED PROCEDURE*/
DELIMITER $$
CREATE PROCEDURE SP_INSERIR_PRODUTO_SUPERMERCADO(
	IN P_COD_BARRAS 		VARCHAR(100),
    IN P_NOME 				VARCHAR(50),
    IN P_PESO 				FLOAT,
    IN P_QUANTIDADE 		INT,
    IN P_PRECO 				FLOAT,
    IN P_DATA_VALIDADE 		DATE,
    IN P_SUPERMERCADO_CNPJ 	VARCHAR(15)
)
BEGIN 
	DECLARE ULTIMO_PRO_ID INT;
    INSERT INTO PRODUTO (PRO_CODIGO_BARRAS, PRO_NOME, PRO_PESO, PRO_QUANTIDADE, PRO_PRECO, PRO_DATA_VALIDADE)
	VALUES 				(P_COD_BARRAS, P_NOME, P_PESO, P_QUANTIDADE, P_PRECO, P_DATA_VALIDADE);
    
    SET ULTIMO_PRO_ID = LAST_INSERT_ID();
    
    INSERT INTO SUPERMERCADO_PRODUTO(FK_SUP_CNPJ, FK_PRO_ID)
    VALUES 							(P_SUPERMERCADO_CNPJ, ULTIMO_PRO_ID);
END $$
DELIMITER ;

CALL SP_INSERIR_PRODUTO_SUPERMERCADO('1234444556', 'Pringles Stranger Things', 135, 20, 12.50, '2026-10-03', 12335678000101);


/*EXERCÍCIO 1 - VIEW*/
CREATE VIEW VW_PRODUTOS_VENCIMENTO AS
SELECT 	P.PRO_NOME AS "NOME DO PRODUTO",
        P.PRO_PRECO AS "PREÇO DO PRODUTO",
        P.PRO_QUANTIDADE AS "QUANTIDADE DO PRODUTO",
        P.PRO_DATA_VALIDADE AS "DATA DE VENCIMENTO",
        TIMESTAMPDIFF(DAY, P.PRO_DATA_VALIDADE, NOW()) AS "DIAS PARA VENCER"
FROM 	PRODUTO P
WHERE 	TIMESTAMPDIFF(DAY, P.PRO_DATA_VALIDADE, NOW()) <= 15;

SELECT * FROM VW_PRODUTOS_VENCIMENTO;

