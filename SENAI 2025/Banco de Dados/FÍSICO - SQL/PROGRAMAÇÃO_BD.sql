SELECT * FROM VW_FUNCIONARIOS_SUPERMERCADO;


/*FUNCTIONS*/
DELIMITER $$
CREATE FUNCTION FUN_CALCULA_DESCONTO(
	P_PRECO 	DOUBLE,
    P_DESCONTO	DOUBLE
)
RETURNS DOUBLE
DETERMINISTIC
BEGIN
	DECLARE PRECO_FINAL DOUBLE;
    SET PRECO_FINAL = P_PRECO - (P_PRECO * (P_DESCONTO/100));
    RETURN PRECO_FINAL;
END $$
DELIMITER ;

SELECT 	FUN_CALCULA_DESCONTO(249.90, 40) FROM DUAL;

SELECT 	PRO_NOME,
		PRO_PRECO,
        FUN_CALCULA_DESCONTO(PRO_PRECO, 50) AS "PREÇO COM DESCONTO"
FROM 	PRODUTO;


