CREATE TRIGGER TRI_VALIDA_QTD_PRODUTO 
BEFORE INSERT ON PRODUTO 
FOR EACH ROW
BEGIN 
	IF NEW.PRO_QUANTIDADE <= 0 THEN 
		SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'QUANTIDADE DEVE SER MAIOR QUE 0';
	END IF;
END $$
