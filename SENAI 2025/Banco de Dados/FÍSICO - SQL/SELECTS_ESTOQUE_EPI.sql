CREATE DATABASE IF NOT EXISTS BD_ESTOQUE_EPI;
USE BD_ESTOQUE_EPI;

CREATE TABLE IF NOT EXISTS FUNCIONARIO(
	FUN_CPF VARCHAR(14) PRIMARY KEY,
    FUN_NOME VARCHAR(255) NOT NULL,
	FUN_EMAIL VARCHAR(255) NOT NULL,
    FUN_TEL VARCHAR(15) NOT NULL UNIQUE,
    FUN_DATA_NASC DATE,
    FUN_AREA VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS FORNECEDOR(
	FOR_CNPJ VARCHAR(20) PRIMARY KEY,
    FOR_NOME VARCHAR(255) NOT NULL,
    FOR_TEL VARCHAR(15) NOT NULL UNIQUE,
    FOR_END_NUM VARCHAR(5) NOT NULL,
    FOR_END_RUA VARCHAR(255) NOT NULL,
    FOR_END_CIDADE VARCHAR(255) NOT NULL,
    FOR_DATA_ENTREGA DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS PRODUTOR(
	PRO_CNPJ VARCHAR(20) PRIMARY KEY,
    PRO_NOME VARCHAR(255) NOT NULL,
    PRO_TEL VARCHAR(15) NOT NULL UNIQUE,
    PRO_END_NUM VARCHAR(5) NOT NULL,
    PRO_END_RUA VARCHAR(255) NOT NULL,
    PRO_END_CIDADE VARCHAR(255) NOT NULL,
    PRO_TEMPO_PRODUCAO VARCHAR(10) NOT NULL
);

CREATE TABLE IF NOT EXISTS EPI(
	EPI_ID INTEGER AUTO_INCREMENT PRIMARY KEY,
    EPI_VENC DATE NOT NULL,
    EPI_DESC VARCHAR(255),
    EPI_TIPO VARCHAR(255) NOT NULL,
    EPI_DATA_RETIRA DATE NOT NULL,
    EPI_DATA_DEVOLUCAO DATE NOT NULL,
    FK_PRO_CNPJ VARCHAR(20) NOT NULL,
    FK_FUN_CPF VARCHAR(14) NULL,
    FOREIGN KEY (FK_PRO_CNPJ) REFERENCES PRODUTOR(CNPJ),
    FOREIGN KEY (FK_FUN_CPF) REFERENCES FUNCIONARIO(CPF)
);

CREATE TABLE IF NOT EXISTS ESTOQUE(
	ES_ID INTEGER AUTO_INCREMENT PRIMARY KEY,
    ES_QTD_TOTAL VARCHAR(10) NOT NULL,
    FK_EPI_ID INTEGER NOT NULL,
    FOREIGN KEY (FK_EPI_ID) REFERENCES EPI(ID)
);

CREATE TABLE IF NOT EXISTS EPI_FORNECEDOR(
	EPI_FORNECEDOR_ID INTEGER AUTO_INCREMENT PRIMARY KEY,
    FK_FOR_CNPJ VARCHAR(20) NOT NULL,
    FK_EPI_ID INTEGER NOT NULL,
    FOREIGN KEY (FK_FOR_CNPJ) REFERENCES FORNECEDOR(CNPJ),
    FOREIGN KEY (FK_EPI_ID) REFERENCES EPI(ID)
);

